#!/usr/bin/env Rscript
# Purpose: Run pre-ranked GSEA for four macrophage subtypes:
#   LAM, PVM, TIM4+_ATM, TIM4+_CD11c+_ATM
#
# Gene set collections (MSigDB via msigdbr):
#   H      : Hallmarks (50 broad gene sets)
#   KEGG   : C2:CP:KEGG_LEGACY (canonical pathways)
#   GO_BP  : C5:GO:BP (Gene Ontology Biological Process)
#   GO_CC  : C5:GO:CC (Gene Ontology Cellular Component)
#   GO_MF  : C5:GO:MF (Gene Ontology Molecular Function)
#
# Ranking metric: 'scores' column (signed DEG test statistic)
#   - positive = upregulated in this subtype vs others
#   - already captures both direction and magnitude
#
# Input: SECTION4_GSEA_ROOT/DEG_lv2_subtypes.csv with columns group, names,
# and scores. Macrophages from SAT and VAT are represented in the DEG input.
# Output: complete GSEA TSV files under SECTION4_GSEA_ROOT/output/tsv.
# No figures are generated by this script.
# Usage: Rscript macrophage_subtype_gsea.R

suppressPackageStartupMessages({
  library(fgsea)
  library(msigdbr)
  library(dplyr)
  library(tidyr)
  library(tibble)
  library(stringr)
})

set.seed(42)

BASE <- Sys.getenv("SECTION4_GSEA_ROOT")
DIR_TSV  <- file.path(BASE, "output/tsv")
dir.create(DIR_TSV,  recursive = TRUE, showWarnings = FALSE)

SUBTYPES     <- c("LAM", "PVM", "TIM4+_ATM", "TIM4+_CD11c+_ATM")
PADJ_THRESH  <- 0.05
MIN_SIZE     <- 15
MAX_SIZE     <- 500
N_PERM       <- 1000

# ── Load DEG data ─────────────────────────────────────────────────────────────
cat("Loading DEG data...\n")
deg <- read.csv(file.path(BASE, "DEG_lv2_subtypes.csv"), stringsAsFactors = FALSE)
cat(sprintf("  Total rows: %d  |  Subtypes: %s\n",
            nrow(deg), paste(unique(deg$group), collapse = ", ")))

# ── Build pre-ranked gene lists (by scores) ───────────────────────────────────
make_ranked_list <- function(df, subtype) {
  sub <- df %>% filter(group == subtype)
  # Remove duplicated gene symbols (keep the one with higher absolute score)
  sub <- sub %>%
    group_by(names) %>%
    slice_max(abs(scores), n = 1, with_ties = FALSE) %>%
    ungroup()
  rl <- setNames(sub$scores, sub$names)
  sort(rl, decreasing = TRUE)
}

cat("Building ranked gene lists...\n")
ranked_lists <- lapply(setNames(SUBTYPES, SUBTYPES), make_ranked_list, df = deg)
for (s in SUBTYPES) {
  cat(sprintf("  %-25s: %d genes  (range: %.2f to %.2f)\n",
              s, length(ranked_lists[[s]]),
              min(ranked_lists[[s]]), max(ranked_lists[[s]])))
}

# ── Load gene sets from MSigDB ────────────────────────────────────────────────
cat("\nLoading gene sets from MSigDB (human)...\n")

get_msigdbr_df <- function(collection, subcollection = NULL) {
  args <- list(collection = collection)
  if (!is.null(subcollection)) args$subcollection <- subcollection
  do.call(msigdbr, args)
}

# Load raw msigdbr tables (needed for GO ID metadata)
raw_dfs <- list(
  Hallmarks = get_msigdbr_df("H"),
  KEGG      = get_msigdbr_df("C2", "CP:KEGG_LEGACY"),
  GO_BP     = get_msigdbr_df("C5", "GO:BP"),
  GO_CC     = get_msigdbr_df("C5", "GO:CC"),
  GO_MF     = get_msigdbr_df("C5", "GO:MF")
)

# Gene set lists for fgsea (gs_name → gene symbols)
gene_sets <- lapply(raw_dfs, function(df) split(df$gene_symbol, df$gs_name))

# Pathway metadata: gs_name → pathway_name (clean) + go_id
# gs_exact_source holds the GO term ID for GO collections
pathway_meta <- bind_rows(lapply(names(raw_dfs), function(coll) {
  df <- raw_dfs[[coll]]
  df %>%
    select(gs_name, gs_exact_source) %>%
    distinct() %>%
    mutate(
      collection   = coll,
      pathway_name = gs_name %>%
        gsub("^HALLMARK_", "", .) %>%
        gsub("^KEGG_",     "", .) %>%
        gsub("^GOBP_",     "", .) %>%
        gsub("^GOCC_",     "", .) %>%
        gsub("^GOMF_",     "", .) %>%
        gsub("_", " ", .) %>%
        str_to_title(),
      go_id = ifelse(grepl("^GO:", gs_exact_source), gs_exact_source, NA_character_)
    ) %>%
    select(gs_name, collection, pathway_name, go_id)
}))

for (coll in names(gene_sets)) {
  cat(sprintf("  %-12s: %d gene sets\n", coll, length(gene_sets[[coll]])))
}

# ── Run fgsea ─────────────────────────────────────────────────────────────────
cat("\nRunning fgsea (this may take a few minutes for GO_BP)...\n")

all_results <- list()

for (subtype in SUBTYPES) {
  rl <- ranked_lists[[subtype]]
  for (coll in names(gene_sets)) {
    cat(sprintf("  %-25s x %-12s ...", subtype, coll))

    res <- fgsea(
      pathways    = gene_sets[[coll]],
      stats       = rl,
      minSize     = MIN_SIZE,
      maxSize     = MAX_SIZE,
      nPermSimple = N_PERM
    )

    res <- res %>%
      as_tibble() %>%
      mutate(subtype = subtype) %>%
      # Join pathway metadata (clean name, GO ID, collection label)
      left_join(pathway_meta %>% filter(collection == coll),
                by = c("pathway" = "gs_name")) %>%
      mutate(direction = ifelse(NES > 0, "up", "down")) %>%
      arrange(padj, desc(abs(NES)))

    # Count significant pathways
    n_sig <- sum(res$padj < PADJ_THRESH, na.rm = TRUE)
    cat(sprintf(" %d significant\n", n_sig))

    key <- paste(subtype, coll, sep = "__")
    all_results[[key]] <- res
  }

  # ── Save TSV per subtype x collection ────────────────────────────────────
  rl <- ranked_lists[[subtype]]  # named score vector for this subtype

  safe_name <- gsub("\\+", "plus", gsub("[^A-Za-z0-9_]", "_", subtype))
  for (coll in names(gene_sets)) {
    res_coll <- all_results[[paste(subtype, coll, sep = "__")]] %>%
      mutate(leadingEdge = lapply(leadingEdge, function(genes) {
        genes[order(rl[genes], decreasing = TRUE)]
      })) %>%
      mutate(leadingEdge = sapply(leadingEdge, paste, collapse = ",")) %>%
      select(pathway, pathway_name, collection, go_id,
             subtype, direction, NES, padj, pval, ES, log2err, size,
             leadingEdge) %>%
      arrange(desc(NES))

    tsv_out <- file.path(DIR_TSV, sprintf("gsea_%s_%s.tsv", safe_name, coll))
    write.table(res_coll, tsv_out, sep = "\t", row.names = FALSE, quote = FALSE)
    cat(sprintf("  Saved: %s\n", basename(tsv_out)))
  }
}

cat("\nfgsea complete. TSVs saved to output/tsv/\n")

message("GSEA analysis complete. Results: ", DIR_TSV)
